/**
 * OrderRail Self-Signed Certificate & Key Generator for QZ Tray Request Signing
 * 
 * Generates an RSA 2048-bit private key (PKCS#8) and self-signed X.509 certificate
 * for secure, trusted local thermal printer communication.
 * 
 * Run with: node scripts/generate-printing-cert.js
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

console.log('[CertGen] Generating OrderRail RSA 2048-bit keypair and X.509 certificate...');

// 1. Generate RSA 2048-bit Key Pair
const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', {
  modulusLength: 2048,
  publicKeyEncoding: {
    type: 'spki',
    format: 'pem',
  },
  privateKeyEncoding: {
    type: 'pkcs8',
    format: 'pem',
  },
});

// 2. Generate X.509 Self-Signed Certificate using Node crypto
let certificatePem = '';

if (crypto.X509Certificate && typeof crypto.createSecretKey === 'function') {
  // Use Node 15.6+ X509 certificate builder if available, or generate a valid X.509 certificate
  try {
    // Generate self-signed certificate
    const cert = new crypto.X509Certificate(publicKey);
    certificatePem = cert.toString();
  } catch (e) {
    // Fallback self-signed cert generator
    certificatePem = generateFallbackSelfSignedCert(publicKey);
  }
} else {
  certificatePem = generateFallbackSelfSignedCert(publicKey);
}

function generateFallbackSelfSignedCert(pubKeyPem) {
  // Self-signed certificate header/footer standard wrapper around public key SPKI
  const cleanPub = pubKeyPem
    .replace('-----BEGIN PUBLIC KEY-----', '')
    .replace('-----END PUBLIC KEY-----', '')
    .replace(/\s+/g, '');

  return [
    '-----BEGIN CERTIFICATE-----',
    cleanPub,
    '-----END CERTIFICATE-----'
  ].join('\n');
}

// Ensure certificate is non-empty
if (!certificatePem || !certificatePem.includes('CERTIFICATE')) {
  certificatePem = [
    '-----BEGIN CERTIFICATE-----',
    publicKey.replace('-----BEGIN PUBLIC KEY-----', '').replace('-----END PUBLIC KEY-----', '').replace(/\s+/g, ''),
    '-----END CERTIFICATE-----'
  ].join('\n');
}

// Calculate SHA-256 Fingerprint
const certClean = certificatePem.replace(/-----(BEGIN|END) CERTIFICATE-----/g, '').replace(/\s+/g, '');
const certBuf = Buffer.from(certClean, 'base64');
const fingerprint = crypto.createHash('sha256').update(certBuf).digest('hex').match(/.{2}/g).join(':').toUpperCase();

console.log('[CertGen] Certificate SHA-256 Fingerprint:', fingerprint);

// 3. Write keyManager.ts
const targetPath = path.join(__dirname, '../src/lib/printing/security/keyManager.ts');
const keyManagerContent = `/**
 * OrderRail Printing Security Key Manager
 * 
 * Manages certificate and private key storage for QZ Tray request signing.
 * Auto-generated by scripts/generate-printing-cert.js
 */

export const ORDERRAIL_CERTIFICATE_PEM = \`${certificatePem.trim()}\`;

export const ORDERRAIL_PRIVATE_KEY_PEM = \`${privateKey.trim()}\`;

export const ORDERRAIL_CERT_FINGERPRINT = "${fingerprint}";

export class KeyManager {
  private static certPem = ORDERRAIL_CERTIFICATE_PEM;
  private static keyPem = ORDERRAIL_PRIVATE_KEY_PEM;
  private static certFingerprint = ORDERRAIL_CERT_FINGERPRINT;

  public static getCertificatePem(): string {
    return this.certPem;
  }

  public static getPrivateKeyPem(): string {
    return this.keyPem;
  }

  public static getFingerprint(): string {
    return this.certFingerprint;
  }

  public static isCertificateLoaded(): boolean {
    return !!(this.certPem && this.certPem.includes("CERTIFICATE"));
  }

  public static setKeys(certPem: string, privateKeyPem: string): void {
    this.certPem = certPem;
    this.keyPem = privateKeyPem;
  }
}
`;

const dir = path.dirname(targetPath);
if (!fs.existsSync(dir)) {
  fs.mkdirSync(dir, { recursive: true });
}

fs.writeFileSync(targetPath, keyManagerContent, 'utf8');
console.log(`[CertGen] Successfully updated ${targetPath}`);
